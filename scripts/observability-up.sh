#!/usr/bin/env bash
# Start Prometheus and Grafana natively (no Docker) against the lab node.
#
#   scripts/observability-up.sh
#
# Everything runtime goes to .obs/ (git-ignored): generated configs, TSDB, Grafana data, logs, pid files.
# The node itself is NOT started here: run scripts/start-node.sh --period 1 first.
#
# Settings (environment, all optional):
#   PROM_HOME     folder with prometheus + promtool   (default: found on PATH, else the author's tools folder)
#   GRAFANA_HOME  Grafana folder with bin/grafana     (default: found on PATH, else the author's tools folder)
#   PROM_PORT     default 9090      GRAFANA_PORT   default 3000
#   METRICS_PORT  node metrics port, default 6060 (same variable as start-node.sh)
#   GRAFANA_PASSWORD  admin password, default "lab-throwaway" (loopback only, local throwaway instance)
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

OBS="$LAB_ROOT/.obs"
PROM_PORT="${PROM_PORT:-9090}"
GRAFANA_PORT="${GRAFANA_PORT:-3000}"
GRAFANA_PASSWORD="${GRAFANA_PASSWORD:-lab-throwaway}"
TOOLS="${LAB_TOOLS:-/c/Users/srg/tools/observability}"

# Windows-style path for files that native Windows programs read (YAML contents); identity elsewhere.
wpath() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi; }

find_prom() {
  if [ -n "${PROM_HOME:-}" ]; then echo "$PROM_HOME"; return; fi
  if command -v prometheus >/dev/null 2>&1; then dirname "$(command -v prometheus)"; return; fi
  ls -d "$TOOLS"/prometheus-*/ 2>/dev/null | head -1 | sed 's:/$::'
}
find_grafana() {
  if [ -n "${GRAFANA_HOME:-}" ]; then echo "$GRAFANA_HOME"; return; fi
  if command -v grafana >/dev/null 2>&1; then dirname "$(dirname "$(command -v grafana)")"; return; fi
  ls -d "$TOOLS"/grafana-*/ 2>/dev/null | head -1 | sed 's:/$::'
}
exe() { if [ -x "$1.exe" ]; then echo "$1.exe"; else echo "$1"; fi; }

PH="$(find_prom)"; GH="$(find_grafana)"
[ -n "$PH" ] && [ -x "$(exe "$PH/prometheus")" ] || die "prometheus not found (set PROM_HOME)"
[ -n "$GH" ] && [ -x "$(exe "$GH/bin/grafana")" ] || die "grafana not found (set GRAFANA_HOME)"
PROM_BIN="$(exe "$PH/prometheus")"; PROMTOOL="$(exe "$PH/promtool")"; GRAFANA_BIN="$(exe "$GH/bin/grafana")"

mkdir -p "$OBS/prom-data" "$OBS/grafana/data" "$OBS/grafana/logs" "$OBS/grafana/plugins" \
         "$OBS/grafana/provisioning/datasources" "$OBS/grafana/provisioning/dashboards"
ensure_nodectl
for f in prometheus grafana; do
  if [ -f "$OBS/$f.pid" ] && "$LAB_ROOT/bin/nodectl" alive "$(cat "$OBS/$f.pid")"; then
    die "$f already running (pid $(cat "$OBS/$f.pid")); run scripts/observability-down.sh first"
  fi
done

# --- Prometheus: the Docker config targets host.docker.internal; the native one targets loopback. ---
cat > "$OBS/prometheus.yml" <<YAML
# Generated by scripts/observability-up.sh. Edit monitoring/prometheus/*.yml and re-run the script, not this file.
global:
  scrape_interval: 5s
  evaluation_interval: 5s
rule_files:
  - $(wpath "$LAB_ROOT/monitoring/prometheus/alerts.yml")
scrape_configs:
  - job_name: geth
    metrics_path: /debug/metrics/prometheus
    static_configs:
      - targets: ["127.0.0.1:$METRICS_PORT"]
        labels:
          instance: dev-node
YAML
say "promtool check"
"$PROMTOOL" check config "$(wpath "$OBS/prometheus.yml")"

say "starting Prometheus on 127.0.0.1:$PROM_PORT"
"$LAB_ROOT/bin/nodectl" start -log "$OBS/prometheus.log" -pid "$OBS/prometheus.pid" -- "$PROM_BIN" \
  --config.file="$(wpath "$OBS/prometheus.yml")" --storage.tsdb.path="$(wpath "$OBS/prom-data")" \
  --web.listen-address="127.0.0.1:$PROM_PORT" --storage.tsdb.retention.time=2d >/dev/null

# --- Grafana: provisioning generated with loopback URLs and the repo's dashboard folder. ---
cat > "$OBS/grafana/provisioning/datasources/prometheus.yml" <<YAML
apiVersion: 1
datasources:
  - name: Prometheus
    uid: prometheus
    type: prometheus
    access: proxy
    url: http://127.0.0.1:$PROM_PORT
    isDefault: true
YAML
cat > "$OBS/grafana/provisioning/dashboards/dashboards.yml" <<YAML
apiVersion: 1
providers:
  - name: geth-lab
    folder: geth-lab
    type: file
    options:
      path: $(wpath "$LAB_ROOT/monitoring/grafana/dashboards")
YAML

say "starting Grafana on 127.0.0.1:$GRAFANA_PORT"
GF_PATHS_DATA="$(wpath "$OBS/grafana/data")" GF_PATHS_LOGS="$(wpath "$OBS/grafana/logs")" \
GF_PATHS_PLUGINS="$(wpath "$OBS/grafana/plugins")" GF_PATHS_PROVISIONING="$(wpath "$OBS/grafana/provisioning")" \
GF_SECURITY_ADMIN_PASSWORD="$GRAFANA_PASSWORD" GF_SERVER_HTTP_ADDR=127.0.0.1 GF_SERVER_HTTP_PORT="$GRAFANA_PORT" \
GF_ANALYTICS_REPORTING_ENABLED=false GF_ANALYTICS_CHECK_FOR_UPDATES=false \
"$LAB_ROOT/bin/nodectl" start -log "$OBS/grafana.log" -pid "$OBS/grafana.pid" -- "$GRAFANA_BIN" server \
  --homepath "$(wpath "$GH")" >/dev/null

wait_http() { # url name timeout-seconds
  local i=0
  until curl -fsS -o /dev/null "$1" 2>/dev/null; do
    i=$((i+1)); [ "$i" -gt $(($3*5)) ] && { tail -15 "$OBS/$2.log" >&2; die "$2 did not answer within $3 s"; }; sleep 0.2
  done
}
wait_http "http://127.0.0.1:$PROM_PORT/-/ready" prometheus 30
ok "Prometheus ready:  http://127.0.0.1:$PROM_PORT  (pid $(cat "$OBS/prometheus.pid"))"
wait_http "http://127.0.0.1:$GRAFANA_PORT/api/health" grafana 90
ok "Grafana ready:     http://127.0.0.1:$GRAFANA_PORT  (admin / $GRAFANA_PASSWORD, pid $(cat "$OBS/grafana.pid"))"
say "dashboard: http://127.0.0.1:$GRAFANA_PORT/d/geth-lab-overview"
